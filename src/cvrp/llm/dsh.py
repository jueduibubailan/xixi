"""The DeepSeek Harness (``dsh``) agent runtime.

Mirrors what CORAL does for this runtime (`agents.runtime: dsh`):

* spawns ``dsh --profile headless <prompt>`` in the stage worktree;
* writes the instruction to ``AGENTS.md`` at the worktree root, because that is the file
  DSH reads -- while our own stages keep their ``CVPR.md``, which the other runtimes and
  the diagnostics use;
* points ``DSH_HOME`` at a shared ``.dsh/`` so consecutive stages inherit context, and
  passes the permission and tool modes through the environment DSH expects;
* reads the final assistant text out of the streamed log.

The CLI is not installed in this repository's environment, so nothing here is verified
against a live binary. What *is* verifiable -- the argv, the environment and the log
parsing -- is asserted in `tests/test_dsh_backend.py`, and a missing binary produces a
message that says what to install rather than an empty result.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

from cvrp.llm.base import LLMBackend, LLMResult, extract_json_payload
from cvrp.llm.claude_code import MAX_CAPTURED_CHARS, _clean_env, result_text_from_log

#: Written next to the stage instruction because DSH reads `AGENTS.md` at the worktree root.
AGENTS_FILE = "AGENTS.md"

#: Environment variables DSH itself reads, per CORAL's agent-runtimes guide.
DSH_HOME_VAR = "DSH_HOME"
PERMISSION_VAR = "DSH_PERMISSION_MODE"
TOOLS_VAR = "DSH_TOOLS_MODE"

#: The API key and base URL DSK honours for model traffic.
API_KEY_VAR = "DEEPSEEK_API_KEY"
BASE_URL_VAR = "DEEPSEEK_BASE_URL"

DEFAULT_PROFILE = "headless"


def resolve_dsh_binary(binary: str) -> str:
    """Return an executable path for the DeepSeek Harness CLI."""
    candidate = Path(binary).expanduser()
    if candidate.is_file():
        return str(candidate)
    found = shutil.which(binary)
    if found:
        return found
    raise FileNotFoundError(
        f"DeepSeek Harness CLI not found ({binary!r}). Install it with "
        "`npm install --global @deepseek-ai/dsh`, make sure `dsh` is on PATH, set "
        "`DEEPSEEK_API_KEY`, or point `llm.runtime_options.command` at the binary."
    )


def build_command(
    prompt: str,
    binary: str = "dsh",
    profile: str = DEFAULT_PROFILE,
    model: str = "",
    patch: list[str] | None = None,
    extra_args: list[str] | None = None,
) -> list[str]:
    """The exact argv used for one turn (kept public so tests can assert on it)."""
    cmd = [binary, "--profile", profile]
    if model:
        cmd.extend(["--model", model])
    for item in patch or []:
        cmd.extend(["--patch", str(item)])
    cmd.extend(extra_args or [])
    cmd.append(prompt)
    return cmd


def write_agents_file(cwd: Path, prompt: str, run_dir: Path | None = None) -> Path:
    """Drop the instruction where DSH looks for it.

    DSH reads `AGENTS.md` from the worktree root. Writing it is idempotent, and the header
    records where the authoritative copy lives so a reader who finds this one knows the
    rendered instruction (`CVPR.md`) is the one the pipeline produced.
    """
    cwd = Path(cwd)
    target = cwd / AGENTS_FILE
    target.parent.mkdir(parents=True, exist_ok=True)
    origin = f"{Path(run_dir) / 'worktrees'}\n" if run_dir else "(pipeline)\n"
    target.write_text(
        "<!-- generated by cvrp; the authoritative copy is CVPR.md in this worktree -->\n"
        f"<!-- run: {origin}-->\n\n" + prompt,
        encoding="utf-8",
    )
    return target


def dsh_env(
    extra: dict[str, str] | None = None,
    *,
    run_dir: Path | None = None,
    inherit_routing: bool = True,
    permission_mode: str = "",
    tools_mode: str = "",
    dsh_home: str = "",
) -> dict[str, str]:
    """The environment for one `dsh` turn."""
    env = _clean_env(dict(extra or {}), inherit_routing=inherit_routing)
    if dsh_home:
        home = Path(dsh_home).expanduser()
        if not home.is_absolute() and run_dir is not None:
            home = Path(run_dir) / home
        home.mkdir(parents=True, exist_ok=True)
        env[DSH_HOME_VAR] = str(home)
    if permission_mode:
        env[PERMISSION_VAR] = permission_mode
    if tools_mode:
        env[TOOLS_VAR] = tools_mode
    return env


class DshBackend(LLMBackend):
    """Launch the DeepSeek Harness in a stage worktree and collect its answer."""

    name = "dsh"

    def __init__(self, llm_config: dict | None = None):
        cfg = dict(llm_config or {})
        options = dict(cfg.get("runtime_options") or {})
        self.model = str(options.get("model") or cfg.get("model") or "")
        self.binary = str(options.get("command") or cfg.get("dsh_bin") or "dsh")
        self.profile = str(options.get("profile") or DEFAULT_PROFILE)
        self.patch = [str(item) for item in (options.get("patch") or cfg.get("patch") or [])]
        self.permission_mode = str(
            options.get("permission_mode") or cfg.get("permission_mode") or ""
        )
        self.tools_mode = str(options.get("tools_mode") or cfg.get("tools_mode") or "")
        self.dsh_home = str(cfg.get("dsh_home") or ".dsh")
        self.extra_args = [str(item) for item in (cfg.get("extra_args") or [])]
        self.env_extra = {str(k): str(v) for k, v in (cfg.get("env") or {}).items()}
        self.inherit_routing_env = bool(cfg.get("inherit_routing_env", True))
        self.run_dir = Path(str(cfg["_run_dir"])) if cfg.get("_run_dir") else None

    # -- introspection ------------------------------------------------------- #

    def command_for(self, prompt: str) -> list[str]:
        """The argv this backend would use, resolved binary included."""
        try:
            binary = resolve_dsh_binary(self.binary)
        except FileNotFoundError:
            binary = self.binary
        return build_command(
            prompt=prompt,
            binary=binary,
            profile=self.profile,
            model=self.model,
            patch=self.patch,
            extra_args=self.extra_args,
        )

    # -- one turn ------------------------------------------------------------ #

    def _header(self, cwd: Path, env: dict[str, str]) -> str:
        """The log header, written before the launch is attempted.

        Recorded first on purpose: when the binary is missing, the log is the only place
        that says which runtime and profile the pipeline was asking for.
        """
        return (
            "# cvrp agent turn (dsh)\n"
            f"# cwd: {Path(cwd).resolve()}\n"
            f"# profile: {self.profile}\n"
            f"# model: {self.model or '(profile default)'}\n"
            f"# {DSH_HOME_VAR}: {env.get(DSH_HOME_VAR, '(inherited)')}\n\n"
        )

    def _write_header(self, log_path: Path, cwd: Path) -> None:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        env = dsh_env(
            self.env_extra,
            run_dir=self.run_dir,
            inherit_routing=self.inherit_routing_env,
            permission_mode=self.permission_mode,
            tools_mode=self.tools_mode,
            dsh_home=self.dsh_home,
        )
        log_path.write_text(self._header(cwd, env), encoding="utf-8")

    def run(self, prompt: str, cwd: Path, log_path: Path, timeout_s: int = 3600) -> LLMResult:
        started = time.time()
        cwd = Path(cwd)
        log_path = Path(log_path)
        log_path.parent.mkdir(parents=True, exist_ok=True)
        write_agents_file(cwd, prompt, self.run_dir)
        self._write_header(log_path, cwd)

        try:
            binary = resolve_dsh_binary(self.binary)
        except FileNotFoundError as exc:
            return LLMResult(
                returncode=127, error=str(exc), backend=self.name, log_path=str(log_path)
            )

        cmd = build_command(
            prompt=prompt,
            binary=binary,
            profile=self.profile,
            model=self.model,
            patch=self.patch,
            extra_args=self.extra_args,
        )
        env = dsh_env(
            self.env_extra,
            run_dir=self.run_dir,
            inherit_routing=self.inherit_routing_env,
            permission_mode=self.permission_mode,
            tools_mode=self.tools_mode,
            dsh_home=self.dsh_home,
        )

        with log_path.open("w", encoding="utf-8", errors="replace") as log_file:
            log_file.write(self._header(cwd, env))
            log_file.flush()
            try:
                proc = subprocess.Popen(
                    cmd,
                    cwd=str(cwd),
                    env=env,
                    stdin=subprocess.DEVNULL,
                    stdout=log_file,
                    stderr=subprocess.STDOUT,
                )
            except OSError as exc:
                return LLMResult(
                    returncode=126,
                    error=f"failed to launch dsh: {exc}",
                    backend=self.name,
                    log_path=str(log_path),
                )
            try:
                returncode = proc.wait(timeout=timeout_s)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
                return LLMResult(
                    text=result_text_from_log(log_path)[:MAX_CAPTURED_CHARS],
                    returncode=124,
                    duration_s=time.time() - started,
                    backend=self.name,
                    log_path=str(log_path),
                    error=f"agent turn exceeded {timeout_s}s and was killed",
                )

        text = result_text_from_log(log_path)
        return LLMResult(
            text=text[:MAX_CAPTURED_CHARS],
            payload=extract_json_payload(text),
            returncode=returncode,
            duration_s=time.time() - started,
            backend=self.name,
            log_path=str(log_path),
            error="" if returncode == 0 else f"dsh exited with code {returncode}",
        )


def describe_environment() -> dict[str, Any]:
    """What a `cvrp doctor` style command wants to know about this runtime."""
    found = shutil.which("dsh")
    return {
        "binary": found or "dsh (not on PATH)",
        "DEEPSEEK_API_KEY": "set" if os.environ.get(API_KEY_VAR) else "unset",
        BASE_URL_VAR: os.environ.get(BASE_URL_VAR, "unset"),
    }
