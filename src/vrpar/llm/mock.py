TEST_TRAIN = """# mock quick train
trainer_params = {
    'epochs': {epochs},
    'train_episodes': {episodes},
    'train_batch_size': 64,
}

def main():
    print('QUICK TRAIN OK')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
"""


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _score_for(prompt: str) -> str:
    """A deterministic score per execution, so tests can exercise both paths."""
    normalized = prompt.replace("\\", "/")
    if "/plan-b1-s01/" in normalized:
        return "41.5000"
    if "/runs/final/" in normalized:
        return "41.0000"
    return "42.0000"


def _int_after(prompt: str, key: str, default: int) -> int:
    match = re.search(rf"'{key}':\s*(\d+)", prompt)
    return int(match.group(1)) if match else default


def _batch_number(prompt: str) -> int:
    for pattern in (r"plans/b(\d+)-s01\.md", r"batch\s+`(\d+)`"):
        match = re.search(pattern, prompt)
        if match:
            return int(match.group(1))
    return 1


def _counts(prompt: str) -> tuple[int, int]:
    """How many strategy/mutation plan files this batch asks for."""
    match = re.search(
        r"Exactly\s+`(\d+)`\s+strategy\s+files\s+and\s+`(\d+)`\s+mutation\s+files", prompt
    )
    return (int(match.group(1)), int(match.group(2))) if match else (10, 2)


NN_PLAN_FILE = """---
id: {id}
batch: {batch}
kind: {kind}
base: {base}
title: {title}
target: CVRPModel.py::Model.__init__
change: {change}
rationale: mock rationale
---

# {id} — {title}

## Change
{change}.

## Why it should lower the cost
Mock rationale.

## Implementation notes
Mirror the change in both the training and the test entry.

## Expected effect and cost
Slightly lower cost; negligible extra cost.

## Risk and rollback
None; revert the mock structure.

## What this plan does not change
Scale, budget, file names, score line.
"""


def _mock_plans(
    batch: int, strategies: int, mutations: int, base: str = "initial"
) -> list[dict]:
    plans = []
    for index in range(strategies):
        plans.append(
            {
                "id": f"b{batch}-s{index + 1:02d}",
                "kind": "strategy",
                "base": base,
                "title": f"mock method {index + 1}",
                "change": "route each node through one of several learned transforms",
            }
        )
    for index in range(mutations):
        plans.append(
            {
                "id": f"b{batch}-m{index + 1:02d}",
                "kind": "mutation",
                "base": base,
                "title": f"mock mutation {index + 1}",
                "change": "add a second decoding pass that revises the first solution",
            }
        )
    return plans


class MockBackend(LLMBackend):
    name = "mock"

    def __init__(self, llm_config: dict | None = None, problem=None):
        self.cfg = dict(llm_config or {})
        self.problem = problem

    def run(self, prompt: str, cwd: Path, log_path: Path, timeout_s: int = 60) -> LLMResult:
        started = time.time()
        cwd = Path(cwd)
        log_path = Path(log_path)
        log_path.parent.mkdir(parents=True, exist_ok=True)

        if "[STAGE:analysis]" in prompt:
            _write(cwd / "artifacts" / "analysis" / "plan.md", PLAN)
            payload = {"status": "ok", "summary": "mock plan", "files": ["artifacts/analysis/plan.md"]}

        elif "[STAGE:code_generation]" in prompt:
            gen = cwd / "artifacts" / "generated"
            _write(gen / "MOCKProblemDef.py", "# mock problem def\n")
            _write(gen / "MOCKEnv.py", "# mock env\n")
            _write(gen / "MOCKModel.py", "# mock model\n")
            _write(gen / "MOCKTrainer.py", "# mock trainer\n")
            _write(gen / "MOCKTester.py", "# mock tester\n")
            _write(gen / "train_n20.py", TRAIN_ENTRY)
            _write(gen / "test_n20.py", TEST_ENTRY)
            _write(gen / "README.md", "# mock deliverable\n")
            payload = {"status": "ok", "summary": "mock generated package"}

        elif "[STAGE:code_error]" in prompt:
            gen = cwd / "artifacts" / "generated"
            key_match = re.search(r"/runs/([^/\s`]+)", prompt)
            runs = cwd / "artifacts" / "runs" / (key_match.group(1) if key_match else "")
            score = _score_for(prompt)
            body = TEST_TRAIN.replace(
                "{epochs}", str(_int_after(prompt, "epochs", 200))
            ).replace("{episodes}", str(_int_after(prompt, "train_episodes", 5000)))
            _write(gen / "test_train.py", body)
            _write(
                gen / f"checkpoint-{_int_after(prompt, 'epochs', 200)}.pt",
                "mock checkpoint\n",
            )
            _write(runs / "test_train.stdout.txt", "QUICK TRAIN OK\n")
            _write(runs / "test_train.stderr.txt", "")
            _write(runs / "test_train.exitcode", "0\n")
            _write(runs / "test.stdout.txt", f" *** Test Done ***\n AUGMENTATION SCORE: {score} \n")
            _write(runs / "test.stderr.txt", "")
            _write(runs / "test.exitcode", "0\n")
            payload = {"status": "ok", "summary": "mock quick test"}

        elif "[STAGE:code_adjustment]" in prompt:
            match = re.search(r"plan id: `([^`]+)`", prompt)
            if match:
                _write(cwd / "artifacts" / "revisions" / f"plan-{match.group(1)}.md", "# mock plan applied\n")
            else:
                _write(cwd / "artifacts" / "revisions" / "round-1.md", "# mock revision\n")
            payload = {"status": "ok", "summary": "mock adjustment"}

        elif "[STAGE:nn_improve]" in prompt:
            batch = _batch_number(prompt)
            strategies, mutations = _counts(prompt)
            plans_dir = cwd / "artifacts" / "nn_improve" / "plans"
            plans_dir.mkdir(parents=True, exist_ok=True)
            for plan in _mock_plans(batch, strategies, mutations):
                _write(
                    plans_dir / f"{plan['id']}.md",
                    NN_PLAN_FILE.format(batch=batch, **plan),
                )
            payload = {"status": "ok", "summary": f"mock batch {batch}"}

        else:
            payload = {"status": "ok", "summary": "mock no-op"}

        text = f"mock turn complete\n\n```json\n{json.dumps(payload, indent=2)}\n```\n"
        log_path.write_text(text, encoding="utf-8")
        return LLMResult(
            text=text,
            payload=payload,
            returncode=0,
            duration_s=time.time() - started,
            backend=self.name,
            log_path=str(log_path),
        )
