"""Offline backend: deterministic artifacts, no model call.

The mock writes the same shape the real agents are asked to write, so the
pipeline, the score parser and the tests can run without a model session.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from vrpar.llm.base import LLMBackend, LLMResult

PLAN = """# Mock plan

- scale: problem_size=20, pomo_size=20, aug_factor=8
- generator: self-designed random instances
- training entry: train_n20.py
- test entry: test_20.py (test_episodes=10*1000, test_data_load.enable=False)
- test_train.py: generated by code_error, epochs=1, train_episodes=64
- score line: AUGMENTATION SCORE: <float>
"""

TRAIN_ENTRY = """# mock training entry
import argparse

PROBLEM_SIZE = 20
POMO_SIZE = 20
trainer_params = {
    'epochs': 8100,
    'train_episodes': 10 * 1000,
    'train_batch_size': 64,
}

def main():
    argparse.ArgumentParser().parse_args()
    print('mock training entry')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
"""

TEST_ENTRY = """# mock test entry
import argparse

PROBLEM_SIZE = 20
POMO_SIZE = 20
tester_params = {
    'test_episodes': 10 * 1000,
    'test_data_load': {'enable': False},
}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--model-path', default=None)
    parser.parse_args()
    print('AUGMENTATION SCORE: 42.0000')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
"""

TEST_TRAIN = """# mock quick train
trainer_params = {
    'epochs': 1,
    'train_episodes': 64,
    'train_batch_size': 64,
}

def main():
    print('QUICK TRAIN OK')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
"""


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class MockBackend(LLMBackend):
    name = "mock"

    def __init__(self, llm_config: dict | None = None, problem=None):
        self.cfg = dict(llm_config or {})
        self.problem = problem

    def run(self, prompt: str, cwd: Path, log_path: Path, timeout_s: int = 60) -> LLMResult:
        started = time.time()
        cwd = Path(cwd)
        log_path = Path(log_path)
        log_path.parent.mkdir(parents=True, exist_ok=True)

        if "[STAGE:analysis]" in prompt:
            _write(cwd / "artifacts" / "analysis" / "plan.md", PLAN)
            payload = {"status": "ok", "summary": "mock plan", "files": ["artifacts/analysis/plan.md"]}

        elif "[STAGE:code_generation]" in prompt:
            gen = cwd / "artifacts" / "generated"
            _write(gen / "MOCKProblemDef.py", "# mock problem def\n")
            _write(gen / "MOCKEnv.py", "# mock env\n")
            _write(gen / "MOCKModel.py", "# mock model\n")
            _write(gen / "MOCKTrainer.py", "# mock trainer\n")
            _write(gen / "MOCKTester.py", "# mock tester\n")
            _write(gen / "train_n20.py", TRAIN_ENTRY)
            _write(gen / "test_20.py", TEST_ENTRY)
            _write(gen / "README.md", "# mock deliverable\n")
            payload = {"status": "ok", "summary": "mock generated package"}

        elif "[STAGE:code_error]" in prompt:
            gen = cwd / "artifacts" / "generated"
            runs = cwd / "artifacts" / "runs"
            _write(gen / "test_train.py", TEST_TRAIN)
            _write(runs / "test_train.stdout.txt", "QUICK TRAIN OK\n")
            _write(runs / "test_train.stderr.txt", "")
            _write(runs / "test_train.exitcode", "0\n")
            _write(runs / "test.stdout.txt", " *** Test Done ***\n AUGMENTATION SCORE: 42.0000 \n")
            _write(runs / "test.stderr.txt", "")
            _write(runs / "test.exitcode", "0\n")
            payload = {"status": "ok", "summary": "mock quick test"}

        elif "[STAGE:code_revise]" in prompt:
            _write(cwd / "artifacts" / "revisions" / "round-1.md", "# mock revision\n")
            payload = {"status": "ok", "summary": "mock revision"}

        else:
            payload = {"status": "ok", "summary": "mock no-op"}

        text = f"mock turn complete\n\n```json\n{json.dumps(payload, indent=2)}\n```\n"
        log_path.write_text(text, encoding="utf-8")
        return LLMResult(
            text=text,
            payload=payload,
            returncode=0,
            duration_s=time.time() - started,
            backend=self.name,
            log_path=str(log_path),
        )
